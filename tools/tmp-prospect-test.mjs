import fs from "node:fs";
import { STEPS } from "../lib/prompts.mjs";
import { resolveAIConfig, generateJson } from "../lib/ai.mjs";
import { searchMany } from "../lib/search.mjs";
import { verifyProspectArtifact } from "../lib/agents.mjs";
const settings = JSON.parse(fs.readFileSync("data/settings.json","utf8"));
const products = JSON.parse(fs.readFileSync("data/products.json","utf8"));
const product = products[0];
const mission = { id:"mis_probe", demo:false, name:"SIRI Velador · España", productId:product.id, goal:"conseguir-mayoristas", markets:["España"], depth:"estandar", tone:"cercano, experto, sin presión", budget:0, maxProspects:12, notes:"" };
const queries = ["tiendas de iluminación y lámparas Madrid","lámparas de diseño Barcelona","showroom iluminación Barcelona","tiendas de diseño e interiorismo Madrid","distribuidores de iluminación Barcelona"];
const t0=Date.now();
const search = await searchMany(settings, queries, { perQuery: 5, pages: 2, onProgress: p => console.log("  search:", p.query, "->", p.found, p.engine) });
console.log("SEARCH done", Date.now()-t0, "ms results:", search.results.length, "pages:", search.pages.length, "errors:", search.errors.length);
console.log("domains:", [...new Set(search.results.map(r=>new URL(r.url).hostname))].join(", "));
const ctx = { mission, product, brand: settings.brand, settings, artifacts: { brief: { tesis: "Vender SIRI a tiendas de iluminación de diseño en España.", publico_primario: "tiendas multimarca de iluminación y diseño" }, research: { conclusion: "Las tiendas de iluminación de diseño de Madrid y Barcelona compran series cortas de autor." } }, learnings: [], search };
const prompt = STEPS.prospecting.prompt(ctx);
const cfg = resolveAIConfig(settings);
const t1=Date.now();
const res = await generateJson(cfg, { system: "Sos Cazador de Compradores. Devolvés JSON válido.", prompt, temperature: 0.35, maxTokens: cfg.maxTokens, expects:"object", attempts:3 });
console.log("AI done", Date.now()-t1, "ms usage:", res.usage, "attempts:", res.attempts, "finish:", res.finishReason);
const raw = res.data.compradores || [];
console.log("raw buyers:", raw.length);
for (const b of raw) console.log("  *", b.nombre, "|", b.web, "|", b.origen, "|", b.tipo);
const artifact = { compradores: raw, segmentos: res.data.segmentos||[], faltantes: res.data.faltantes||[] };
const verified = await verifyProspectArtifact(artifact, { mission, search }, {});
console.log("VERIFIED:", verified.verificacion);
for (const b of verified.compradores) console.log("  OK", b.nombre, "|", b.web || "(sin web)", "|", b.web_estado, "|", b.web_titulo||b.fuente);
for (const d of verified.descartados) console.log("  DESC", d.nombre, "|", d.motivo);
