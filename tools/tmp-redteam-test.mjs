import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { STEPS } from "../lib/prompts.mjs";
import { resolveAIConfig, generateJson } from "../lib/ai.mjs";
const dir = path.join(os.tmpdir(), "dsh-5SAZ9H", "lumbre-e2e-3138bdf3");
const settings = JSON.parse(fs.readFileSync("data/settings.json","utf8"));
const products = JSON.parse(fs.readFileSync("data/products.json","utf8"));
const detail = JSON.parse(fs.readFileSync(path.join(dir, "mission.json"), "utf8"));
const mission = detail.mission;
const product = products.find(p => p.id === mission.productId) || products[0];
const ctx = { mission, product, brand: settings.brand, settings, artifacts: mission.artifacts, learnings: [], search: null };
const prompt = STEPS.redteam.prompt(ctx);
console.log("prompt chars:", prompt.length, "includes buyers:", prompt.includes("COMPRADORES VERIFICADOS"));
const cfg = resolveAIConfig(settings);
const t0 = Date.now();
const res = await generateJson(cfg, { system: "Sos Abogado del Diablo. Devolvés JSON válido.", prompt, temperature: 0.55, maxTokens: cfg.maxTokens, expects: "object", attempts: 3 });
console.log("AI ms:", Date.now()-t0, "usage:", res.usage, "maxTokens:", res.maxTokens);
const rt = res.data;
console.log("veredicto:", rt.veredicto);
console.log("sello:", rt.sello);
for (const a of (rt.agujeros||[])) console.log(" agujero:", a.area, "|", a.problema);
